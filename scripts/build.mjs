// Bundles src/ into one dependency-free file, dist/review-policy.mjs.
// The modules are concatenated in dependency order; their relative
// imports are dropped and their node: imports are hoisted. Exported
// names are unique across modules, so they can share one scope.

import { readFileSync, writeFileSync } from 'node:fs';

const ORDER = ['yaml', 'glob', 'config', 'policy', 'github', 'main', 'cli'];
const root = new URL('../', import.meta.url);
const nodeImports = new Map();
const bodies = [];

for (const name of ORDER) {
  const src = readFileSync(new URL(`src/${name}.mjs`, root), 'utf8');
  const kept = [];
  for (const line of src.split('\n')) {
    const m = /^import \{([^}]+)\} from '([^']+)';$/.exec(line);
    if (m && m[2].startsWith('./')) continue;
    if (m && m[2].startsWith('node:')) {
      const set = nodeImports.get(m[2]) ?? new Set();
      for (const n of m[1].split(',')) set.add(n.trim());
      nodeImports.set(m[2], set);
      continue;
    }
    if (/^import /.test(line)) throw new Error(`src/${name}.mjs: unsupported import: ${line}`);
    kept.push(line);
  }
  bodies.push(`// ---- src/${name}.mjs ----\n${kept.join('\n').trim()}\n`);
}

const header = [
  '// review-policy: generated by scripts/build.mjs from src/. Do not edit.',
  '// https://github.com/lightninglabs/review-policy',
  '',
  ...[...nodeImports].sort().map(([mod, names]) => `import { ${[...names].sort().join(', ')} } from '${mod}';`),
  '',
].join('\n');

writeFileSync(new URL('dist/review-policy.mjs', root), header + '\n' + bodies.join('\n'));
